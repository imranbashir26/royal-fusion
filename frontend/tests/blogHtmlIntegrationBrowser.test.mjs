async function journalFromHeader(page) {
  const response = page.waitForResponse(response => response.request().isNavigationRequest() && new URL(response.url()).pathname === '/blogs')
  await page.locator('header').getByRole('link', { name: 'Journal', exact: true }).click()
  assert.equal((await response).status(), 200)
  await page.getByRole('heading', { name: 'Royal Fusion Journal', exact: true }).waitFor()
  assert.equal(await page.locator('#root').count(), 0)
}
async function shopFromHtml(page) {
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Shop', exact: true }).click()
  await page.getByRole('button', { name: 'Add Baraan to cart', exact: true }).waitFor()
}
function assertOneCheckoutSubmission(state) {
  assert.equal(state.checkout.uiEvents.filter(event => event.event === 'click' && event.label === 'Place Order').length, 1)
  assert.equal(state.checkout.uiEvents.filter(event => event.event === 'click' && event.label === 'Place Order')[0].trusted, true)
  assert.deepEqual(state.checkout.uiEvents.filter(event => event.event === 'submit').map(event => event.trusted), [true])
  assert.equal(state.checkout.applicationFetches.length, 1)
  assert.equal(state.checkout.applicationFetches[0].method, 'POST')
  assert.equal(state.checkout.applicationFetches[0].idempotencyKey, state.orders[0].idempotencyKey)
  assert.deepEqual(state.checkout.browserRequests, [{ method: 'POST', idempotencyKey: state.orders[0].idempotencyKey }])
}

test('direct journal and refresh deliver branded script-free HTML, scoped CSS and safe initial metadata', async t => {
  const { page, state } = await integrationPage(t, { javaScriptEnabled: false })
  const response = await page.goto(`${origin}/blogs/`)
  assert.equal(response.status(), 200)
  assert.match(response.headers()['content-type'], /text\/html; charset=utf-8/)
  assert.match(response.headers()['content-security-policy'], /script-src 'none'/)
  assert.equal(response.headers()['cache-control'], 'no-store')
  assert.equal(await page.locator('script').count(), 0)
  assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), `${configuration.canonicalOrigin}/blogs`)
  assert.equal(await page.locator('link[rel="stylesheet"]').getAttribute('href'), '/blogs/_assets/journal.css')
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.site-header')).backgroundColor === 'rgb(85, 19, 38)')
  assert.equal((await page.reload()).status(), 200)
  assert.ok(state.requests.some(request => request.path === '/blogs/_assets/journal.css'))
})

