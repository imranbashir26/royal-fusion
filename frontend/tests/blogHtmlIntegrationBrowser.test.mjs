test('lost checkout response remains frozen through HTML navigation and retries one idempotent order', async t => {
  const { page, state } = await integrationPage(t, { seedCart: true, observeCheckout: true })
  state.lostResponse = true
  await page.goto(`${origin}/checkout`); await fillCheckout(page)
  const initialCart = await projectedCart(page), initial = await storageSnapshot(page)
  await page.getByRole('button', { name: 'Place Order', exact: true }).click()
  await page.getByRole('alert').waitFor()
  assert.equal(state.orders.length, 1); assert.equal(state.receipts.size, 1)
  assertOneCheckoutSubmission(state)
  assert.deepEqual(state.checkout.controlledLosses, [{ idempotencyKey: state.orders[0].idempotencyKey, orderCount: 1, receiptCount: 1 }])
  const before = await storageSnapshot(page)
  assert.ok(JSON.parse(before.intent).intent)
  // capturePurchase persists instance identities using the store's JSON key order.
  assert.deepEqual(JSON.parse(before.cart), JSON.parse(initial.cart))
  for (const key of ['consumed', 'historical']) assert.equal(before[key], initial[key])
  assert.deepEqual(await projectedCart(page), initialCart)
  await journalFromHeader(page); await shopFromHtml(page)
  assert.deepEqual(await storageSnapshot(page), before)
  await page.goto(`${origin}/checkout`)
  await page.getByRole('heading', { name: 'Saved checkout attempt', exact: true }).waitFor()
  assert.equal(state.orders.length, 1)
  state.lostResponse = false
  const retry = page.getByRole('button', { name: 'Retry saved attempt', exact: true })
  await retry.evaluate(button => { button.click(); button.click() })
  await page.getByRole('heading', { name: /Thank you/ }).waitFor()
  assert.equal(state.orders.length, 2); assert.deepEqual(state.orders[1], state.orders[0]); assert.equal(state.receipts.size, 1)
  assert.equal(state.checkout.applicationFetches.length, 2)
  assert.deepEqual(state.checkout.applicationFetches.map(request => request.idempotencyKey), [state.orders[0].idempotencyKey, state.orders[0].idempotencyKey])
  assert.deepEqual(state.checkout.browserRequests, [0, 1].map(() => ({ method: 'POST', idempotencyKey: state.orders[0].idempotencyKey })))
  assert.equal(state.checkout.controlledLosses.length, 1)
  assert.equal((await projectedCart(page)).items.length, 0)
  const after = await storageSnapshot(page)
  await journalFromHeader(page); await shopFromHtml(page)
  await page.goto(`${origin}/checkout/success`)
  await page.getByRole('heading', { name: /Thank you/ }).waitFor()
  assert.deepEqual(await storageSnapshot(page), after)
  assert.equal((await projectedCart(page)).items.length, 0)
  assert.equal(state.orders.length, 2)
})

test('destroyed responses distinguish transport POST retransmissions from one checkout submission', async t => {
  const { page, state } = await integrationPage(t, { seedCart: true, observeCheckout: true })
  state.destroyResponse = true
  await page.goto(`${origin}/checkout`); await fillCheckout(page)
  const initialCart = await projectedCart(page), initial = await storageSnapshot(page)
  await page.getByRole('button', { name: 'Place Order', exact: true }).click()
  await page.getByRole('alert').waitFor()
  assertOneCheckoutSubmission(state)
  const arrivals = state.requests.filter(request => request.path === '/api/v1/public/orders')
  assert.ok(arrivals.length > 1, 'the destroyed-response diagnostic must observe transport retransmission')
  assert.equal(state.orders.length, arrivals.length)
  assert.ok(arrivals.every(request => request.method === 'POST'))
  for (const order of state.orders) assert.deepEqual(order, state.orders[0])
  assert.equal(state.receipts.size, 1)
  assert.deepEqual(state.receipts.get(state.orders[0].idempotencyKey).request, state.orders[0])
  assert.deepEqual(state.checkout.controlledLosses, [])
  const after = await storageSnapshot(page)
  assert.equal(JSON.parse(after.intent).intent.request.idempotencyKey, state.orders[0].idempotencyKey)
  assert.deepEqual(JSON.parse(after.cart), JSON.parse(initial.cart))
  for (const key of ['consumed', 'historical']) assert.equal(after[key], initial[key])
  assert.deepEqual(await projectedCart(page), initialCart)
  t.diagnostic(JSON.stringify({ trustedSubmits: 1, applicationFetches: 1, browserRequests: 1, httpPosts: arrivals.length,
    distinctIdempotencyKeys: new Set(state.orders.map(order => order.idempotencyKey)).size, mockReceipts: state.receipts.size }))
})

