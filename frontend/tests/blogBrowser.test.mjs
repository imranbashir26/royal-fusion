test('rapid navigation aborts Strict Mode requests and late responses cannot overwrite the next article', async t => {
  const { page, state } = await blogPage(t), hold = state.hold('/fragrance-journal')
  await page.goto(`${origin}/blogs/fragrance-journal`); await hold.started
  await page.getByRole('link', { name: 'Fixture second article', exact: true }).click()
  await page.getByRole('heading', { name: 'Second fragrance story', exact: true }).waitFor()
  hold.release()
  await page.waitForFunction(() => document.querySelector('link[rel="canonical"]')?.href.endsWith('/blogs/second-article'))
  await page.getByRole('heading', { name: 'Fragrance journal', exact: true, level: 3 }).waitFor()
  assert.equal(await page.getByRole('heading', { name: 'Fragrance journal', exact: true, level: 1 }).count(), 0)
  assert.equal(await page.getByRole('heading', { name: 'Fragrance journal', exact: true, level: 3 }).count(), 1)
  assert.ok(state.cancelled.some(path => path.endsWith('/fragrance-journal')))
  await page.getByRole('link', { name: 'Fixture shop', exact: true }).click()
  await page.getByRole('heading', { name: 'Royal Perfume Boutique', exact: true }).waitFor()
  await page.waitForFunction(() => !document.querySelector('link[rel="canonical"]')?.href.includes('/blogs/second-article'))
})
test('a fixture client ignoring cancellation cannot overwrite article state after its late response arrives', async t => {
  const { page, state } = await blogPage(t, { ignoreCancellation: true }), hold = state.hold('/fragrance-journal')
  await page.goto(`${origin}/blogs/fragrance-journal`); await hold.started
  await page.getByRole('link', { name: 'Fixture second article', exact: true }).click()
  await page.getByRole('heading', { name: 'Second fragrance story', exact: true, level: 1 }).waitFor()
  hold.release()
  await page.waitForFunction(() => window.__deliveredBlogSlugs?.includes('fragrance-journal'))
  assert.equal(await page.getByRole('heading', { name: 'Second fragrance story', exact: true, level: 1 }).count(), 1)
  assert.equal(await page.getByRole('heading', { name: 'Fragrance journal', exact: true, level: 1 }).count(), 0)
  assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), `${canonicalOrigin}/blogs/second-article`)
})
